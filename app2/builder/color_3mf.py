"""Standard 3MF sRGB color groups, with a small Prusa face-paint palette."""
import io
import zipfile
import numpy as np

CORE = 'http://schemas.microsoft.com/3dmanufacturing/core/2015/02'
MATERIAL = 'http://schemas.microsoft.com/3dmanufacturing/material/2015/02'
PRUSA = 'http://schemas.slic3r.org/3mf/2017/06'


def palette(colors, count=8):
    """Deterministic palette for slicers that store one filament per triangle."""
    values = np.asarray(colors, float)
    sample = values[::max(1, len(values)//20000)]
    centers = sample[np.linspace(0, len(sample)-1, min(count, len(sample)), dtype=int)].copy()
    for _ in range(12):
        labels = ((sample[:,None]-centers)**2).sum(2).argmin(1)
        centers = np.array([sample[labels==k].mean(0) if np.any(labels==k) else center for k,center in enumerate(centers)])
    centers = np.unique(np.rint(centers).astype(np.uint8), axis=0)
    from scipy.spatial import cKDTree
    return centers, cKDTree(centers).query(values, workers=1)[1]


def paint_code(index):
    state = int(index)+1
    return ('4', '8')[state-1] if state<=2 else '%XC' % (state-3)


def write(path, V, F, C):
    unique, indices = np.unique(C, axis=0, return_inverse=True)
    tones, faces = palette(C[F].astype(float).mean(1))
    with zipfile.ZipFile(path, 'w', zipfile.ZIP_DEFLATED, compresslevel=1, allowZip64=True) as z:
        z.writestr('[Content_Types].xml', '<?xml version="1.0"?><Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/><Default Extension="model" ContentType="application/vnd.ms-package.3dmanufacturing-3dmodel+xml"/></Types>')
        z.writestr('_rels/.rels', '<?xml version="1.0"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Target="/3D/3dmodel.model" Id="rel0" Type="http://schemas.microsoft.com/3dmanufacturing/2013/01/3dmodel"/></Relationships>')
        with z.open('3D/3dmodel.model', 'w', force_zip64=True) as raw:
            with io.TextIOWrapper(raw, encoding='utf-8', newline='\n') as f:
                f.write(f'<?xml version="1.0"?><model unit="millimeter" xml:lang="en-US" xmlns="{CORE}" xmlns:m="{MATERIAL}" xmlns:slic3rpe="{PRUSA}"><metadata name="Application">PointYoink</metadata><metadata name="slic3rpe:Version3mf">1</metadata><metadata name="slic3rpe:MmPaintingVersion">1</metadata><resources><m:colorgroup id="1">')
                for c in unique: f.write('<m:color color="#%02X%02X%02X"/>' % tuple(c))
                f.write('</m:colorgroup><object id="2" type="model"><mesh><vertices>')
                for v in V: f.write('<vertex x="%.9g" y="%.9g" z="%.9g"/>' % tuple(v))
                f.write('</vertices><triangles>')
                for k, tri in enumerate(F):
                    f.write('<triangle v1="%d" v2="%d" v3="%d" pid="1" p1="%d" p2="%d" p3="%d" slic3rpe:mmu_segmentation="%s"/>' % (*tri, *indices[tri], paint_code(faces[k])))
                f.write('</triangles></mesh></object></resources><build><item objectid="2"/></build></model>')
        colors = ';'.join('#%02X%02X%02X' % tuple(c) for c in tones)
        z.writestr('Metadata/Slic3r_PE.config', '; generated by PointYoink\nextruder_colour = '+colors+'\nfilament_colour = '+colors+'\nnozzle_diameter = '+';'.join(['0.4']*len(tones))+'\n')
        z.writestr('Metadata/Slic3r_PE_model.config', '<?xml version="1.0"?><config><object id="2"><volume firstid="0" lastid="%d"><metadata type="volume" key="extruder" value="1"/></volume></object></config>' % (len(F)-1))
